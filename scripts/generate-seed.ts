/**
 * Generates supabase/seed.sql from the mock catalogue so the database starts with
 * exactly what the UI shows today (categories, sellers, products, variants, collections).
 * Customers/orders are NOT seeded — those need real auth users.
 *
 *   npm run db:seed:generate
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { categories, collections, products, sellers, subcategories } from "../src/lib/mock/catalog";

const uuid = (ns: string, key: string) => {
  const h = createHash("md5").update(`${ns}:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: string | number | null | undefined) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map((x) => q(x)).join(", ")}]::text[]`;

const out: string[] = ["-- GENERATED by scripts/generate-seed.ts — do not edit by hand.", "begin;"];

categories.forEach((c, i) =>
  out.push(`insert into public.categories (id, slug, name, tagline, photo_kind, sort) values (${q(uuid("cat", c.slug))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${q(c.photo)}, ${i});`));

Object.entries(subcategories).forEach(([cat, subs]) =>
  subs.forEach((s, i) =>
    out.push(`insert into public.subcategories (id, category_id, name, sort) values (${q(uuid("sub", `${cat}/${s}`))}, ${q(uuid("cat", cat))}, ${q(s)}, ${i});`)));

sellers.forEach((s) =>
  out.push(
    `insert into public.sellers (id, slug, name, owner_name, email, phone, city, state, status, kyc, gstin, commission_pct, blurb, tone_from, tone_to, joined_at) values (` +
      [q(uuid("seller", s.id)), q(s.slug), q(s.name), q(s.owner), q(s.email), q(s.phone), q(s.city), q(s.state), q(s.status), q(s.kyc), q(s.gstin), s.commissionPct, q(s.blurb), q(s.tone[0]), q(s.tone[1]), q(s.joined)].join(", ") + ");"));

products.forEach((p) => {
  const pid = uuid("product", p.id);
  const sub = subcategories[p.categorySlug]?.includes(p.subcategory) ? q(uuid("sub", `${p.categorySlug}/${p.subcategory}`)) : "null";
  out.push(
    `insert into public.products (id, slug, seller_id, category_id, subcategory_id, name, description, price, mrp, option_label, material, care, details, tags, badges, photo_kind, status, rating_avg, review_count, sold_count, created_at) values (` +
      [q(pid), q(p.slug), q(uuid("seller", p.sellerId)), q(uuid("cat", p.categorySlug)), sub, q(p.name), q(p.description), p.price, p.mrp, q(p.optionLabel), q(p.fabric), arr(p.care), arr(p.details), arr(p.tags), arr(p.badges), q(p.photo), q(p.status), p.rating, p.reviewCount, p.sold, q(p.createdAt)].join(", ") + ");");
  p.colors.forEach((c, i) => out.push(`insert into public.product_colors (id, product_id, name, hex, sort) values (${q(uuid("color", `${p.id}/${c.name}`))}, ${q(pid)}, ${q(c.name)}, ${q(c.hex)}, ${i});`));
  p.sizes.forEach((s, i) => out.push(`insert into public.product_options (id, product_id, value, stock, sort) values (${q(uuid("opt", `${p.id}/${s}`))}, ${q(pid)}, ${q(s)}, ${p.stock[s] ?? 0}, ${i});`));
});

collections.forEach((c, i) => {
  out.push(`insert into public.collections (id, slug, name, story, photo_kind, sort) values (${q(uuid("col", c.slug))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.story)}, ${q(c.photo)}, ${i});`);
  c.productIds.forEach((id, n) => out.push(`insert into public.collection_products (collection_id, product_id, sort) values (${q(uuid("col", c.slug))}, ${q(uuid("product", id))}, ${n});`));
});

out.push("commit;");
writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
// ---- supabase/fashion-v2.sql: the same data, preceded by a wipe of the demo catalogue (for a database seeded with an older version)
const demoSellers = [...sellers.map((s) => s.slug), "voltedge", "hearth-and-home", "glow-theory", "spice-route", "indigo-loom"].map((s) => `'${s}'`).join(", ");
const reset = [
  "-- ManaBrand: Men / Women fashion catalogue (Footwear coming soon).",
  "-- GENERATED by scripts/generate-seed.ts. Run once in Supabase -> SQL Editor.",
  "--",
  "-- WARNING: this DELETES every product, category, collection and ORDER in the database, plus the sample sellers,",
  "-- then loads the new catalogue. Use it only while the data is still demo data. Real sellers' accounts are kept",
  "-- (their products are removed, so they re-add them). Not needed on a fresh database: seed.sql already has the new catalogue.",
  "begin;",
  "delete from public.orders;",
  "delete from public.products;",
  "delete from public.collections;",
  "delete from public.categories;",
  `delete from public.payouts where seller_id in (select id from public.sellers where slug in (${demoSellers}));`,
  `delete from public.sellers where slug in (${demoSellers});`,
  ...out.slice(2, -1),
  "commit;",
];
writeFileSync("supabase/fashion-v2.sql", reset.join("\n") + "\n");
console.log(`seed.sql written: ${categories.length} categories, ${sellers.length} sellers, ${products.length} products, ${collections.length} collections`);
